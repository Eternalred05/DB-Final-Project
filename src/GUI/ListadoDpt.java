    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int filasSeleccionadas = tablaDepartamentos.getSelectedRows().length;
        boolean puedeModificar = false;
        if (filasSeleccionadas == 1) {
            puedeModificar = true;
        } else {
            JOptionPane.showMessageDialog(this,
                    "Seleccione solo un departamento para modificar.",
                    "Error al escoger departamento", JOptionPane.WARNING_MESSAGE);
        }

        if (puedeModificar) {
            int fila = tablaDepartamentos.getSelectedRow();
            DefaultTableModel model = (DefaultTableModel) tablaDepartamentos.getModel();
            String codDpt = model.getValueAt(fila, 0).toString();

            Departamento departamento = departamentoDAO.obtenerDepartamentoPorCodigo(codDpt);
            boolean departamentoExiste = (departamento != null);

            if (!departamentoExiste) {
                JOptionPane.showMessageDialog(this,
                        "No se encontró el departamento en la base de datos.",
                        "Error", JOptionPane.ERROR_MESSAGE);
            }

            if (departamentoExiste) {
                EditDpt dialog = new EditDpt(null, true, departamento);
                dialog.setLocationRelativeTo(this);
                dialog.setVisible(true);

                cargarTabla();
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int filas = tablaDepartamentos.getSelectedRows().length;
        if (filas != 1) {
            JOptionPane.showMessageDialog(null, "Seleccione solo un Departamento", "Error", JOptionPane.ERROR_MESSAGE);
        } else {
            int fila = tablaDepartamentos.getSelectedRow();
            DefaultTableModel model = (DefaultTableModel) tablaDepartamentos.getModel();
            String codDpt = model.getValueAt(fila, 0).toString();
            String nombreDpt = model.getValueAt(fila, 1).toString();

            int confirm = JOptionPane.showConfirmDialog(this,
                    "¿Eliminar el departamento \"" + nombreDpt + "\" (" + codDpt + ")?",
                    "Confirmar eliminación", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                try {
                    departamentoDAO.eliminarDepartamento(codDpt);
                    JOptionPane.showMessageDialog(this, "Departamento eliminado correctamente.");
                    cargarTabla();
                } catch (RuntimeException ex) {
                    JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

