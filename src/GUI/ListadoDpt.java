    private void configurarTabla() {
        String[] columnas = {"Código", "Nombre", "ID Hospital"};
        DefaultTableModel model = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tablaDepartamentos.setModel(model);
        tablaDepartamentos.getTableHeader().setReorderingAllowed(false);
    }

    private void cargarTabla() {
        DefaultTableModel model = (DefaultTableModel) tablaDepartamentos.getModel();
        model.setRowCount(0);
        ArrayList<Departamento> lista = departamentoDAO.listarDpt();
        for (Departamento d : lista) {
            model.addRow(new Object[]{
                d.getId(),
                d.getName(),
                d.getIdHosp()
            });
        }
    }

