    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int filas = tablaTurnos.getSelectedRows().length;
        boolean puedeEliminar = false;
        if (filas == 1) {
            puedeEliminar = true;
        } else {
            JOptionPane.showMessageDialog(this, "Seleccione solo un turno para eliminar.");
        }
        if (puedeEliminar) {
            int fila = tablaTurnos.getSelectedRow();
            DefaultTableModel model = (DefaultTableModel) tablaTurnos.getModel();
            String codUnidad = model.getValueAt(fila, 8).toString();
            int numTurno = (int) model.getValueAt(fila, 3);
            int informes = turnoDAO.contarInformesDeTurno(codUnidad, numTurno);
            boolean puedeBorrar = true;
            if (informes > 0) {
                JOptionPane.showMessageDialog(this,
                        "El turno tiene " + informes + " informe(s) asociado(s). Elimínelos primero.");
                puedeBorrar = false;
            }
            if (puedeBorrar) {
                int confirm = JOptionPane.showConfirmDialog(this,
                        "¿Eliminar el turno " + numTurno + " de la unidad " + codUnidad + "?",
                        "Confirmar eliminación", JOptionPane.YES_NO_OPTION);
                if (confirm == JOptionPane.YES_OPTION) {
                    try {
                        turnoDAO.eliminarTurno(codUnidad, numTurno);
                        JOptionPane.showMessageDialog(this, "Turno eliminado correctamente.");
                        cargarTabla();
                    } catch (RuntimeException ex) {
                        JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                    }
                }
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int filas = tablaTurnos.getSelectedRows().length;
        boolean puedeEditar = false;
        if (filas == 1) {
            puedeEditar = true;
        } else {
            JOptionPane.showMessageDialog(this, "Seleccione solo un turno para editar.");
        }
        if (puedeEditar) {
            int fila = tablaTurnos.getSelectedRow();
            DefaultTableModel model = (DefaultTableModel) tablaTurnos.getModel();
            String codUnidad = model.getValueAt(fila, 8).toString();
            int numTurno = (int) model.getValueAt(fila, 3);
            Turno turno = turnoDAO.obtenerTurno(codUnidad, numTurno);
            if (turno != null) {
                EditTurno dialog = new EditTurno(null, true, turno);
                dialog.setLocationRelativeTo(null);
                dialog.setVisible(true);
                cargarTabla();
            } else {
                JOptionPane.showMessageDialog(this, "Turno no encontrado.");
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

