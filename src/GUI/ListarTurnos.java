    private void configurarTabla() {
        String[] columnas = {"Hospital", "Depto", "Unidad", "Turno", "Pac. asignados",
            "Pac. atendidos", "Médico", "codMedico", "codUnidad"};
        DefaultTableModel model = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tablaTurnos.setModel(model);
        tablaTurnos.getTableHeader().setReorderingAllowed(false);

        tablaTurnos.getColumnModel().getColumn(7).setMinWidth(0);
        tablaTurnos.getColumnModel().getColumn(7).setMaxWidth(0);
        tablaTurnos.getColumnModel().getColumn(7).setWidth(0);
        tablaTurnos.getColumnModel().getColumn(8).setMinWidth(0);
        tablaTurnos.getColumnModel().getColumn(8).setMaxWidth(0);
        tablaTurnos.getColumnModel().getColumn(8).setWidth(0);
    }

    private void cargarTabla() {
        DefaultTableModel model = (DefaultTableModel) tablaTurnos.getModel();
        model.setRowCount(0);
        try {
            ArrayList<TurnoListado> lista = turnoDAO.listarTurnos();
            for (TurnoListado tl : lista) {
                model.addRow(new Object[]{
                    tl.getHospital(), tl.getDepartamento(), tl.getUnidad(),
                    tl.getNumTurno(), tl.getCantPacientes(), tl.getPacientesAtend(),
                    tl.getNombreMedico(), tl.getCodMedico(), tl.getCodUnidad()
                });
            }
        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

