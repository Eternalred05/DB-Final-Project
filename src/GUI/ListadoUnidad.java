    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int filasSeleccionadas = tablaUnidades.getSelectedRows().length;
        boolean puedeModificar = false;
        if (filasSeleccionadas == 1) {
            puedeModificar = true;
        } else {
            JOptionPane.showMessageDialog(this,
                    "Seleccione solo una unidad para modificar.",
                    "Error", JOptionPane.WARNING_MESSAGE);
        }

        if (puedeModificar) {
            int fila = tablaUnidades.getSelectedRow();
            DefaultTableModel model = (DefaultTableModel) tablaUnidades.getModel();
            String codUnidad = model.getValueAt(fila, 0).toString();
            Unidad unidad = unidadDAO.obtenerUnidadPorCodigo(codUnidad);
            boolean unidadExiste = (unidad != null);
            if (!unidadExiste) {
                JOptionPane.showMessageDialog(this,
                        "No se encontró la unidad en la base de datos.",
                        "Error", JOptionPane.ERROR_MESSAGE);
            }
            if (unidadExiste) {
                EditUnidad dialog = new EditUnidad(null, true, unidad);
                dialog.setLocationRelativeTo(this);
                dialog.setVisible(true);
                cargarTabla();
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int filasSeleccionadas = tablaUnidades.getSelectedRows().length;
        boolean puedeEliminar = false;
        if (filasSeleccionadas == 1) {
            puedeEliminar = true;
        } else {
            JOptionPane.showMessageDialog(this,
                    "Seleccione solo una unidad para eliminar.",
                    "Error", JOptionPane.WARNING_MESSAGE);
        }

        if (puedeEliminar) {
            int fila = tablaUnidades.getSelectedRow();
            DefaultTableModel model = (DefaultTableModel) tablaUnidades.getModel();
            String codUnidad = model.getValueAt(fila, 0).toString();
            String nombreUnidad = model.getValueAt(fila, 1).toString();

            int medicos = unidadDAO.contarMedicosEnUnidad(codUnidad);
            boolean puedeBorrar = true;
            if (medicos > 0) {
                JOptionPane.showMessageDialog(this,
                        "La unidad \"" + nombreUnidad + "\" tiene " + medicos + " médico(s) asignado(s).\n"
                        + "Elimine primero los médicos de esta unidad.",
                        "Eliminación no permitida", JOptionPane.WARNING_MESSAGE);
                puedeBorrar = false;
            }

            if (puedeBorrar) {
                int confirm = JOptionPane.showConfirmDialog(this,
                        "¿Eliminar la unidad \"" + nombreUnidad + "\" (" + codUnidad + ")?",
                        "Confirmar eliminación", JOptionPane.YES_NO_OPTION);
                if (confirm == JOptionPane.YES_OPTION) {
                    try {
                        unidadDAO.eliminarUnidad(codUnidad);
                        JOptionPane.showMessageDialog(this, "Unidad eliminada correctamente.");
                        cargarTabla();
                    } catch (RuntimeException ex) {
                        JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                    }
                }
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

