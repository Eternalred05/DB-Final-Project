    private void configurarTabla() {
        String[] columnas = {"Código", "Nombre", "Ubicación", "Depto"};
        DefaultTableModel model = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tablaUnidades.setModel(model);
        tablaUnidades.getTableHeader().setReorderingAllowed(false);
    }

    private void cargarTabla() {
        DefaultTableModel model = (DefaultTableModel) tablaUnidades.getModel();
        model.setRowCount(0);
        ArrayList<Unidad> lista = unidadDAO.listarUnidades();
        for (Unidad u : lista) {
            model.addRow(new Object[]{
                u.getId(),
                u.getName(),
                u.getLocation(),
                u.getCodDpt()
            });
        }
    }

